/**
 * BlazorHero's translations, from its resx files to Tsazor's string tables (docs/port-blazorhero.md, phase 1):
 *
 *   node scripts/resx.mjs        (after `pnpm backend` cloned upstream)
 *
 * writes src/i18n/<culture>.ts — the client's resources and the Application project's validators' messages —, one
 * flat table per culture with the key `<Resource>.<name>` ("Login.Title"). A resource belongs to the component or
 * class of its path, as .NET finds it by the type's name (Resources/Pages/Authentication/Login.de.resx →
 * Pages/Authentication/Login.razor); a resource without one is stale and left out. Arabic file names that start with right-to-left marks (U+200F) are read under their
 * real name (U2: .NET never finds them).
 */
import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const upstream = path.join(root, ".backend", "blazor-starter-kit", "src");
const out = path.join(root, "src", "i18n");
/**
 * The projects whose resources the client reads, and the folder in each: of the Application project only the
 * validators (its handlers' messages come translated from the server).
 */
const PROJECTS = [
  ["Client", ""],
  ["Client.Infrastructure", ""],
  ["Application", "Validators"],
];
const MARKS = /^[​‎‏]+/;

function* resxFiles(dir) {
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) yield* resxFiles(full);
    else if (entry.name.endsWith(".resx")) yield full;
  }
}

const ENTITIES = { amp: "&", lt: "<", gt: ">", quot: '"', apos: "'" };
function decode(text) {
  return text.replace(/&(#x[0-9a-f]+|#\d+|amp|lt|gt|quot|apos);/gi, (match, entity) => {
    if (entity[0] === "#") return String.fromCodePoint(entity[1] === "x" ? parseInt(entity.slice(2), 16) : Number(entity.slice(1)));
    return ENTITIES[entity.toLowerCase()] ?? match;
  });
}

/** The string entries of a resx file: name → value (comments and typed entries left out). */
function entries(file) {
  const xml = readFileSync(file, "utf8").replace(/<!--[\s\S]*?-->/g, "");
  const result = {};
  for (const [, attributes, body] of xml.matchAll(/<data\s([^>]*)>([\s\S]*?)<\/data>/g)) {
    if (/\stype="/.test(` ${attributes}`)) continue;
    const name = /name="([^"]*)"/.exec(attributes)?.[1];
    const value = /<value>([\s\S]*?)<\/value>/.exec(body)?.[1];
    if (name !== undefined && value !== undefined) result[decode(name)] = decode(value);
  }
  return result;
}

/** A source file of `dir` that declares `class <name>` (a localization marker class beside its component). */
function declaring(dir, name) {
  if (!existsSync(dir)) return undefined;
  const pattern = new RegExp(`\\bclass\\s+${name}\\b`);
  return readdirSync(dir)
    .filter((file) => /\.(cs|razor)$/.test(file))
    .map((file) => path.join(dir, file))
    .find((file) => pattern.test(readFileSync(file, "utf8")));
}

const tables = {};
const owners = new Map();
const stale = new Set();
let marked = 0;
for (const [project, only] of PROJECTS) {
  const resources = path.join(upstream, project, "Resources");
  for (const file of resxFiles(path.join(resources, only))) {
    const raw = path.basename(file);
    const name = raw.replace(MARKS, "");
    if (name !== raw) marked++;
    const match = /^(.+)\.([A-Za-z_-]+)\.resx$/.exec(name);
    if (!match) throw new Error(`resx: no culture in ${path.relative(upstream, file)}`);
    const [, resource, culture] = match;
    const folder = path.relative(resources, path.dirname(file));
    const source = ["razor", "cs"].map((ext) => path.join(upstream, project, folder, `${resource}.${ext}`)).find(existsSync) ?? declaring(path.join(upstream, project, folder), resource);
    const id = `${project}/${folder}/${resource}`.replace(/\\/g, "/");
    if (!source) {
      stale.add(id);
      continue;
    }
    const owner = owners.get(resource);
    if (owner !== undefined && owner !== id) throw new Error(`resx: two resources are called ${resource} (${owner}, ${id})`);
    owners.set(resource, id);
    const table = (tables[culture.toLowerCase()] ??= {});
    for (const [key, value] of Object.entries(entries(file))) table[`${resource}.${key}`] = value;
  }
}

mkdirSync(out, { recursive: true });
for (const [culture, table] of Object.entries(tables)) {
  const lines = Object.keys(table)
    .sort()
    .map((key) => `  ${JSON.stringify(key)}: ${JSON.stringify(table[key])},`);
  writeFileSync(
    path.join(out, `${culture}.ts`),
    `// GENERATED by scripts/resx.mjs from BlazorHero's resx files (${culture}) — do not edit by hand.\n\n` +
      `export default {\n${lines.join("\n")}\n} as const;\n`,
  );
}
console.log(
  `resx: ${Object.keys(tables).length} cultures (${Object.entries(tables).map(([c, t]) => `${c} ${Object.keys(t).length}`).join(", ")}); ` +
    `${owners.size} resources, ${stale.size} stale left out (${[...stale].join(", ")}); ${marked} file names with right-to-left marks.`,
);
