/**
 * Writes src/Components/IconName.ts: FluentCMS's own icons (its UI library's IconResource.resx, the `IconName` enum)
 * as app icons made with `icon()`, so the port writes `IconName.Delete` as the original does (design-icons.md
 * step 6). Run after `node scripts/backend.mjs` has cloned FluentCMS into .backend/:
 *
 *   node scripts/icons.mjs
 */
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const resx = path.join(root, ".backend", "FluentCMS", "src", "Frontend", "FluentCMS.Web.UI.Components", "Components", "Icon", "IconResource.resx");
const unescape = (text) => text.replace(/&lt;/g, "<").replace(/&gt;/g, ">").replace(/&quot;/g, '"').replace(/&apos;/g, "'").replace(/&amp;/g, "&");
const kebab = (name) => name.replace(/([a-z0-9])([A-Z])/g, "$1-$2").toLowerCase();

const icons = [];
for (const match of readFileSync(resx, "utf8").matchAll(/<data name="([A-Za-z]+)"[^>]*>\s*<value>([\s\S]*?)<\/value>/g)) {
  const [, name, value] = match;
  // The original's Default is an empty placeholder: "no icon" is `undefined` here.
  if (name === "Default") continue;
  icons.push({ name, svg: unescape(value).trim() });
}
icons.sort((a, b) => a.name.localeCompare(b.name));

const lines = [
  "// Generated by scripts/icons.mjs from FluentCMS's IconResource.resx (MIT License, Copyright (c) 2024 FluentCMS) — do not edit.",
  "/**",
  " * FluentCMS's own icons (its `IconName` enum), as app icons: `<ActionButton IconName=\"@IconName.Delete\" />`.",
  " */",
  'import { icon, type IconValue } from "@tsazor/fluent";',
  "",
  "export const IconName = {",
  ...icons.map(({ name, svg }) => `  ${name}: icon(${JSON.stringify(kebab(name))}, ${JSON.stringify(svg)}),`),
  "} as const satisfies Record<string, IconValue>;",
  "",
  "/** One of FluentCMS's icon names. */",
  "export type IconName = keyof typeof IconName;",
  "",
];
writeFileSync(path.join(root, "src", "Components", "IconName.ts"), lines.join("\n"));
console.log(`[fluentcms] ${icons.length} icons from IconResource.resx`);
