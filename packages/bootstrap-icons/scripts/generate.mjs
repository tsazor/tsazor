/**
 * Generates @tsazor/bootstrap-icons from bootstrap-icons (design-icons.md §3.2): one ES module that exports every icon
 * as an `IconValue` of @tsazor/ui (`Alarm`, `AlarmFill`, …), so `Icons.Alarm` is typed and a bundler keeps only the
 * icons a page reaches. A name that starts with a digit gets `Number` in front (`0-circle` → `Number0Circle`).
 */
import { mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const require = createRequire(import.meta.url);
const sourcePackage = path.dirname(require.resolve("bootstrap-icons/package.json"));
const sourceVersion = JSON.parse(readFileSync(path.join(sourcePackage, "package.json"), "utf8")).version;
const iconsDir = path.join(sourcePackage, "icons");
const dist = path.join(root, "dist");

/** `alarm-fill` → `AlarmFill`; `0-circle` → `Number0Circle`. */
function exportNameOf(name) {
  const pascal = name.split("-").map((part) => part.charAt(0).toUpperCase() + part.slice(1)).join("");
  return /^[0-9]/.test(pascal) ? `Number${pascal}` : pascal;
}

const icons = [];
const taken = new Map();
for (const file of readdirSync(iconsDir).sort()) {
  if (!file.endsWith(".svg")) continue;
  const name = file.slice(0, -4);
  const svg = readFileSync(path.join(iconsDir, file), "utf8");
  const whole = /^\s*<svg\b([^>]*)>([\s\S]*)<\/svg>\s*$/.exec(svg);
  if (whole === null) throw new Error(`${file}: not a single <svg> element`);
  const exportName = exportNameOf(name);
  if (taken.has(exportName)) throw new Error(`${file}: ${exportName} is taken by ${taken.get(exportName)}`);
  taken.set(exportName, file);
  const viewBox = /\bviewBox="([^"]*)"/.exec(whole[1])?.[1] ?? "0 0 16 16";
  // One line per element, as the source has them on their own lines.
  const content = whole[2].split("\n").map((line) => line.trim()).filter(Boolean).join("");
  icons.push({ exportName, name, viewBox, content });
}

rmSync(dist, { recursive: true, force: true });
mkdirSync(dist, { recursive: true });
const header = `// Generated by @tsazor/bootstrap-icons from bootstrap-icons ${sourceVersion} (MIT, The Bootstrap Authors) — do not edit.\n`;
writeFileSync(
  path.join(dist, "index.js"),
  header + icons.map((i) => `export const ${i.exportName} = { name: ${JSON.stringify(i.name)}, viewBox: ${JSON.stringify(i.viewBox)}, content: ${JSON.stringify(i.content)} };\n`).join(""),
);
writeFileSync(
  path.join(dist, "index.d.ts"),
  header + `import type { IconValue } from "@tsazor/ui";\n` + icons.map((i) => `export declare const ${i.exportName}: IconValue;\n`).join(""),
);
console.log(`[tsazor/bootstrap-icons] ${icons.length} icons from bootstrap-icons ${sourceVersion}`);
