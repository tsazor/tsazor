/**
 * Writes src/core-icons.ts: the icons the skin's own components draw (the grid's sort arrows), copied from
 * @tsazor/bootstrap-icons, so the skin doesn't depend on the whole set (design-icons.md, D-I4; Fluent UI Blazor's
 * CoreIcons). test/core-icons.test.ts keeps the copies equal to the set.
 *
 *   node scripts/core-icons.mjs        (after `pnpm --filter @tsazor/bootstrap-icons build`)
 */
import { writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import * as Icons from "@tsazor/bootstrap-icons";

/** The set's own names (`Icons.CaretUpFill`). */
const CORE = ["ArrowDownUp", "CaretDownFill", "CaretUpFill", "CheckLg", "PersonFill"];

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const lines = [
  "// Generated by scripts/core-icons.mjs from @tsazor/bootstrap-icons (Bootstrap Icons, MIT) — do not edit.",
  "/**",
  " * The icons the skin's own components draw: copies of @tsazor/bootstrap-icons' values, so the skin doesn't depend",
  " * on the whole set. test/core-icons.test.ts keeps them equal to it.",
  " */",
  'import type { IconValue } from "@tsazor/ui";',
  "",
];
for (const name of CORE) {
  const value = Icons[name];
  if (value === undefined) throw new Error(`${name}: not in @tsazor/bootstrap-icons`);
  lines.push(`export const ${name}: IconValue = ${JSON.stringify(value)};`);
}
writeFileSync(path.join(root, "src", "core-icons.ts"), `${lines.join("\n")}\n`);
console.log(`[tsazor/bootstrap] ${CORE.length} core icons`);
