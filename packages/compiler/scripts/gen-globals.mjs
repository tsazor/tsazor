/**
 * Generates src/globals.generated.ts: the JS/DOM value globals the expression
 * rewriter leaves free (roadmap A4 rule "JS/DOM global ⇒ unchanged"). The set
 * is derived from the installed TypeScript's lib.es*.d.ts and lib.dom*.d.ts —
 * every top-level value declaration (var/let/const, function, class, enum,
 * namespace), minus the ones TypeScript marks `@deprecated` (window.name,
 * window.status, event, …: common member names that must not win as globals).
 *
 *   node scripts/gen-globals.mjs          writes the file
 *   node scripts/gen-globals.mjs --check  exits 1 when it is out of date
 */
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import path from "node:path";
import { fileURLToPath } from "node:url";

const require = createRequire(import.meta.url);
const ts = require("typescript");
const here = path.dirname(fileURLToPath(import.meta.url));
const target = path.resolve(here, "../src/globals.generated.ts");

export function collectGlobals() {
  const libDir = path.dirname(require.resolve("typescript/lib/lib.d.ts"));
  const files = readdirSync(libDir).filter((f) => /^lib\.(es5|es\d{4}|esnext|dom)(\.[\w.]+)?\.d\.ts$/.test(f) && !f.includes(".full."));
  const names = new Set();
  for (const file of files) {
    const source = ts.createSourceFile(file, readFileSync(path.join(libDir, file), "utf8"), ts.ScriptTarget.Latest, true);
    for (const statement of source.statements) {
      if (ts.getJSDocTags(statement).some((tag) => tag.tagName.text === "deprecated")) continue;
      if (ts.isVariableStatement(statement)) {
        for (const declaration of statement.declarationList.declarations) {
          if (ts.isIdentifier(declaration.name)) names.add(declaration.name.text);
        }
      } else if (
        (ts.isFunctionDeclaration(statement) || ts.isClassDeclaration(statement) || ts.isEnumDeclaration(statement) ||
          (ts.isModuleDeclaration(statement) && ts.getModuleInstanceState?.(statement) !== 0)) &&
        statement.name && ts.isIdentifier(statement.name)
      ) {
        names.add(statement.name.text);
      }
    }
  }
  return { files, names: [...names].sort() };
}

export function render({ names }) {
  const lines = [];
  let line = " ";
  for (const name of names.map((n) => JSON.stringify(n))) {
    if (line.length + name.length + 2 > 100) {
      lines.push(line.trimEnd());
      line = " ";
    }
    line += ` ${name},`;
  }
  lines.push(line.trimEnd());
  return [
    "/* Generated by scripts/gen-globals.mjs from TypeScript's lib.es*.d.ts / lib.dom*.d.ts — do not edit. */",
    "",
    "/** JS/DOM value globals (non-deprecated top-level value declarations of the TS libs). */",
    "export const LIB_GLOBALS: ReadonlySet<string> = new Set([",
    ...lines,
    "]);",
    "",
  ].join("\n");
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const text = render(collectGlobals());
  if (process.argv.includes("--check")) {
    const current = readFileSync(target, "utf8");
    if (current.replace(/\r\n/g, "\n") !== text) {
      console.error("src/globals.generated.ts is out of date — run node scripts/gen-globals.mjs");
      process.exit(1);
    }
  } else {
    writeFileSync(target, text);
    console.log(`wrote ${path.relative(process.cwd(), target)}`);
  }
}
