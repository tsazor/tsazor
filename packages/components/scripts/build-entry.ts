import { compile, type ResolvedComponent, type ResolvedType } from "@tsazor/compiler";
import { collectCodeImports, collectImports, createFileContext } from "@tsazor/workspace";
import { transformSync } from "esbuild";
import { mkdir, readdir, readFile, rm, writeFile } from "node:fs/promises";
import path from "node:path";

const packageDir = path.resolve(path.dirname(new URL(import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, "$1")), "..");
const srcDir = path.join(packageDir, "src");
const distDir = path.join(packageDir, "dist");

interface CompileError {
  file: string;
  details: string;
}

const errors: CompileError[] = [];
const exports: string[] = [];

await rm(distDir, { recursive: true, force: true });
await mkdir(distDir, { recursive: true });

const files = (await readdir(srcDir)).filter((name) => name.endsWith(".tsazor") && name !== "_Imports.tsazor").sort();

for (const file of files) {
  const filePath = path.join(srcDir, file);
  const className = path.basename(file, ".tsazor");
  try {
    const source = await readFile(filePath, "utf8");
    const chain = await collectImports(srcDir, packageDir);
    const context = createFileContext(filePath, chain);

    // Pass 1 compiles without extra imports so the code-import scan can see
    // which bindings the compiler emitted itself (same as the Vite plugin).
    const first = compile(source, {
      className: context.className,
      fileName: filePath,
      resolveComponent: (tagName, usings): ResolvedComponent | null => context.resolveComponent(tagName, usings),
      resolveType: (name, usings): ResolvedType | null => context.resolveType(name, usings),
      generateSourceMap: false,
    });
    const extraImports = collectCodeImports(source, first.code, context);

    const compiled = compile(source, {
      className: context.className,
      fileName: filePath,
      resolveComponent: (tagName, usings): ResolvedComponent | null => context.resolveComponent(tagName, usings),
      resolveType: (name, usings): ResolvedType | null => context.resolveType(name, usings),
      imports: extraImports,
      generateSourceMap: false,
    });

    const diagnostics = compiled.diagnostics.all.filter((d) => d.severity === "error");
    if (diagnostics.length > 0) {
      errors.push({
        file,
        details: diagnostics.map((d) => `  ${d.code} (${d.pos.line}:${d.pos.column}): ${d.message}`).join("\n"),
      });
      continue;
    }

    const transpiled = transformSync(compiled.code, {
      loader: "ts",
      sourcefile: filePath,
      tsconfigRaw: {
        compilerOptions: {
          experimentalDecorators: true,
          useDefineForClassFields: false,
          target: "es2022",
        },
      },
    });

    // Sibling component imports point at .tsazor sources; the built library
    // ships compiled .js siblings, so rewrite the specifiers.
    const js = transpiled.code.replace(/(from\s*")(\.\.?\/[^"]*)\.tsazor(")/g, "$1$2.js$3");
    await writeFile(path.join(distDir, `${className}.js`), js);
    exports.push(`export { default as ${className} } from "./${className}.js";`);
  } catch (error) {
    errors.push({ file, details: `  ${error instanceof Error ? error.stack : String(error)}` });
  }
}

if (errors.length > 0) {
  for (const error of errors) {
    console.error(`[tsazor/components] compile errors in ${error.file}\n${error.details}`);
  }
  process.exit(1);
}

const index = `${exports.map((line) => `${line};`).join("\n")}\n`;
await writeFile(path.join(distDir, "index.js"), index);

// Loose ambient types for the POC: the real class types come from the
// compiled modules; editors should not fail on the bare package import.
const types = files
  .map((file) => path.basename(file, ".tsazor"))
  .map((name) => `export const ${name}: any;`)
  .join("\n");
await writeFile(path.join(distDir, "index.d.ts"), `// Generated by the library build (POC: permissive types).\n${types}\n`);

console.log(`[tsazor/components] built ${files.length} components -> dist/`);