/**
 * Generates @tsazor/fluent-icons from @fluentui/svg-icons (design-icons.md §3.2): one ES module per variant and size
 * (dist/regular/size20.js exports `Add`, `Delete`, …), joined by `export * as` namespaces, so
 * `Icons.Regular.Size20.Add` is typed and a bundler keeps only the icons a page reaches. Each icon is an `IconValue`
 * of @tsazor/ui: its name, its viewBox and the SVG's inner markup.
 *
 * The localized variants (icons/<language>/…) are left out for now.
 */
import { mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const require = createRequire(import.meta.url);
const sourcePackage = path.dirname(require.resolve("@fluentui/svg-icons/package.json"));
const sourceVersion = JSON.parse(readFileSync(path.join(sourcePackage, "package.json"), "utf8")).version;
const iconsDir = path.join(sourcePackage, "icons");
const dist = path.join(root, "dist");

const VARIANTS = { regular: "Regular", filled: "Filled", light: "Light", color: "Color" };
const FILE = /^([a-z0-9_]+)_(\d+)_(regular|filled|light|color)\.svg$/;

/** `access_time` → `AccessTime`. */
const pascal = (stem) => stem.split("_").map((part) => part.charAt(0).toUpperCase() + part.slice(1)).join("");

/** variant → size → [{ exportName, name, viewBox, content }] */
const sets = new Map();
for (const file of readdirSync(iconsDir).sort()) {
  const match = FILE.exec(file);
  if (match === null) continue;
  const [, stem, size, variant] = match;
  const svg = readFileSync(path.join(iconsDir, file), "utf8");
  const whole = /^\s*<svg\b([^>]*)>([\s\S]*)<\/svg>\s*$/.exec(svg);
  if (whole === null) throw new Error(`${file}: not a single <svg> element`);
  const viewBox = /\bviewBox="([^"]*)"/.exec(whole[1])?.[1] ?? `0 0 ${size} ${size}`;
  const bySize = sets.get(variant) ?? new Map();
  sets.set(variant, bySize);
  const icons = bySize.get(Number(size)) ?? [];
  bySize.set(Number(size), icons);
  icons.push({ exportName: pascal(stem), name: stem.replaceAll("_", "-"), viewBox, content: whole[2].trim() });
}

rmSync(dist, { recursive: true, force: true });
const header = `// Generated by @tsazor/fluent-icons from @fluentui/svg-icons ${sourceVersion} (MIT, Microsoft) — do not edit.\n`;
const write = (file, text) => {
  mkdirSync(path.dirname(file), { recursive: true });
  writeFileSync(file, header + text);
};

let total = 0;
const variantExports = [];
for (const [variant, bySize] of [...sets].sort(([a], [b]) => a.localeCompare(b))) {
  const sizeExports = [];
  for (const [size, icons] of [...bySize].sort(([a], [b]) => a - b)) {
    const module = `size${size}`;
    write(
      path.join(dist, variant, `${module}.js`),
      icons.map((i) => `export const ${i.exportName} = { name: ${JSON.stringify(i.name)}, viewBox: ${JSON.stringify(i.viewBox)}, content: ${JSON.stringify(i.content)} };\n`).join(""),
    );
    write(
      path.join(dist, variant, `${module}.d.ts`),
      `import type { IconValue } from "@tsazor/ui";\n` + icons.map((i) => `export declare const ${i.exportName}: IconValue;\n`).join(""),
    );
    sizeExports.push(`export * as Size${size} from "./${module}.js";\n`);
    total += icons.length;
  }
  write(path.join(dist, variant, "index.js"), sizeExports.join(""));
  write(path.join(dist, variant, "index.d.ts"), sizeExports.join(""));
  variantExports.push(`export * as ${VARIANTS[variant]} from "./${variant}/index.js";\n`);
}
write(path.join(dist, "index.js"), variantExports.join(""));
write(path.join(dist, "index.d.ts"), variantExports.join(""));
console.log(`[tsazor/fluent-icons] ${total} icons from @fluentui/svg-icons ${sourceVersion}`);
