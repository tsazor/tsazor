/**
 * Writes src/core-icons.ts: the icons the skin's own components draw (Alert's status, the close buttons, the pager's
 * chevrons, the grid's sort arrows), copied from @tsazor/fluent-icons. Fluent UI Blazor does the same with its
 * internal CoreIcons, so the skin doesn't depend on the whole set (design-icons.md, D-I4). test/core-icons.test.ts
 * keeps the copies equal to the set.
 *
 *   node scripts/core-icons.mjs        (after `pnpm --filter @tsazor/fluent-icons build`)
 */
import { writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import * as Icons from "@tsazor/fluent-icons";

/** `Name` + size + variant, as Fluent UI React names them (`Dismiss20Regular`). */
const CORE = [
  "ArrowSort20Regular",
  "ArrowSortDown20Regular",
  "ArrowSortUp20Regular",
  "Checkmark12Regular",
  "CheckmarkCircle20Filled",
  "Circle20Filled",
  "Circle20Regular",
  "ChevronDoubleLeft20Regular",
  "ChevronDoubleRight20Regular",
  "ChevronLeft20Regular",
  "ChevronRight12Regular",
  "ChevronRight20Regular",
  "Dismiss12Regular",
  "Dismiss20Regular",
  "DismissCircle20Filled",
  "Info20Filled",
  "Person20Regular",
  "Warning20Filled",
];

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const lines = [
  "// Generated by scripts/core-icons.mjs from @tsazor/fluent-icons (Fluent System Icons, MIT, Microsoft) — do not edit.",
  "/**",
  " * The icons the skin's own components draw (Fluent UI Blazor's CoreIcons): copies of @tsazor/fluent-icons' values,",
  " * so the skin doesn't depend on the whole set. test/core-icons.test.ts keeps them equal to it.",
  " */",
  'import type { IconValue } from "@tsazor/ui";',
  "",
];
for (const exportName of CORE) {
  const [, name, size, variant] = /^(.+?)(\d+)(Regular|Filled)$/.exec(exportName) ?? [];
  const value = Icons[variant]?.[`Size${size}`]?.[name];
  if (value === undefined) throw new Error(`${exportName}: not in @tsazor/fluent-icons`);
  lines.push(`export const ${exportName}: IconValue = ${JSON.stringify(value)};`);
}
writeFileSync(path.join(root, "src", "core-icons.ts"), `${lines.join("\n")}\n`);
console.log(`[tsazor/fluent] ${CORE.length} core icons`);
