/**
 * Generates src/runtime-manifest.generated.ts: the parameter metadata of
 * @tsazor/runtime's built-in components (and their abstract bases), extracted
 * from packages/runtime/src by the same extractor that builds every package
 * manifest (runtime's own build writes the identical dist/tsazor-components.json).
 * Embedded so tag resolution and completion know the built-ins without an
 * installed runtime (bundled language server, temp workspaces).
 *
 *   node scripts/gen-runtime-manifest.mjs          writes the file (needs a built workspace dist)
 *   node scripts/gen-runtime-manifest.mjs --check  exits 1 when it is out of date
 */
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const target = path.resolve(here, "../src/runtime-manifest.generated.ts");
const runtimeDir = path.resolve(here, "../../runtime");

export async function renderRuntimeManifest() {
  const { buildRuntimeManifest } = await import(pathToFileURL(path.resolve(here, "../dist/index.js")).href);
  const manifest = buildRuntimeManifest(runtimeDir);
  return [
    "// Generated by scripts/gen-runtime-manifest.mjs from packages/runtime/src — do not edit.",
    'import type { ComponentManifest } from "@tsazor/compiler";',
    "",
    `export const RUNTIME_MANIFEST: ComponentManifest = ${JSON.stringify(manifest, null, 2)};`,
    "",
  ].join("\n");
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const text = await renderRuntimeManifest();
  if (process.argv.includes("--check")) {
    const current = readFileSync(target, "utf8").replace(/\r\n/g, "\n");
    if (current !== text) {
      console.error("src/runtime-manifest.generated.ts is out of date — run node scripts/gen-runtime-manifest.mjs");
      process.exit(1);
    }
  } else {
    writeFileSync(target, text);
    console.log(`wrote ${path.relative(process.cwd(), target)}`);
  }
}
