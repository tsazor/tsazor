#!/usr/bin/env node
/**
 * docs/library-texts.md: every reserved text key — the library texts (`tsazor.ui.*`) and the validation messages
 * (`tsazor.validation.*`) — with its English and German text and the components that show it, found in the sources
 * of the skins, @tsazor/ui and @tsazor/charts. Generated, so it can't drift from the catalog.
 *
 * Usage: node scripts/library-texts-doc.mjs [--check]   (needs @tsazor/ui built; --check fails when the page is stale)
 */
import { readdirSync, readFileSync, writeFileSync, existsSync } from "node:fs";
import { basename, dirname, join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const repo = dirname(dirname(fileURLToPath(import.meta.url)));
const ui = (file) => pathToFileURL(join(repo, "packages", "ui", "dist", file)).href;
const { libraryTextDefaults } = await import(ui("library-texts.js"));
const { germanFrameworkTexts } = await import(ui("texts/de.js"));

const SOURCES = [
  ["Fluent", "packages/fluent/src"],
  ["Bootstrap", "packages/bootstrap/src"],
  ["ui", "packages/ui/src"],
  ["charts", "packages/charts/src"],
];
const SKIP = new Set(["library-texts.ts", "de.ts"]);

/** Every source file's text, by the package it belongs to and its component name. */
const files = SOURCES.flatMap(([pkg, dir]) => walk(join(repo, dir)).map((path) => ({ pkg, name: basename(path).replace(/\.tsazor(\.ts)?$|\.ts$/, ""), text: readFileSync(path, "utf8") })));

function walk(dir) {
  return readdirSync(dir, { withFileTypes: true }).flatMap((entry) => {
    const path = join(dir, entry.name);
    if (entry.isDirectory()) return walk(path);
    return /\.(ts|tsazor)$/.test(entry.name) && !SKIP.has(entry.name) ? [path] : [];
  });
}

/** Where a library text shows up: the components whose source names it (a counted text by its base name). */
function usedBy(name) {
  const base = name.replace(/\.(zero|one|two|few|many|other)$/, "");
  const found = new Map();
  for (const file of files) {
    // By its name, or by a template that builds it: `dataGrid.operator.${operator}`.
    const parts = base.split(".");
    const templates = parts.slice(0, -1).map((_, i) => "`" + parts.slice(0, i + 1).join(".") + ".${");
    if (!file.text.includes(`"${base}"`) && !file.text.includes(`'${base}'`) && !templates.some((prefix) => file.text.includes(prefix))) continue;
    if (!found.has(file.pkg)) found.set(file.pkg, new Set());
    found.get(file.pkg).add(file.name);
  }
  return [...found].map(([pkg, names]) => `${pkg}: ${[...names].sort().join(", ")}`).join("; ") || "not used by a component (kept so a table's entry still type-checks)";
}

const cell = (text) => String(text).replace(/\|/g, "\\|").replace(/\n/g, " ");
const VALIDATION_ENGLISH = {
  required: "The {displayName} field is required.",
  minLength: "The field {displayName} must be a string or array type with a minimum length of '{min}'.",
  maxLength: "The field {displayName} must be a string or array type with a maximum length of '{max}'.",
  stringLength: "The field {displayName} must be a string with a maximum length of {max}.",
  stringLengthIncludingMinimum: "The field {displayName} must be a string with a minimum length of {min} and a maximum length of {max}.",
  range: "The field {displayName} must be between {min} and {max}.",
  precision: "The field {displayName} must have at most {precision} digits with {scale} decimal places.",
  emailAddress: "The {displayName} field is not a valid e-mail address.",
  regularExpression: "The field {displayName} must match the regular expression '{pattern}'.",
  compare: "'{displayName}' and '{other}' do not match.",
};

const lines = [
  "# The framework's texts",
  "",
  "<!-- Generated by scripts/library-texts-doc.mjs from @tsazor/ui's catalog; don't edit by hand. -->",
  "",
  "Every text Tsazor shows by itself has a reserved key in the app's string tables: the components' texts",
  "`tsazor.ui.<name>`, the built-in validation messages `tsazor.validation.<kind>`. An app's table entry wins over the",
  "English text; a component's own text parameter wins over both ([design-localization.md](design-localization.md), §4).",
  "A German app starts from `germanFrameworkTexts`:",
  "",
  "```ts",
  'import { germanFrameworkTexts } from "@tsazor/ui/texts/de";',
  "",
  'export default { ...germanFrameworkTexts, "Orders.Title": "Bestellungen" } satisfies StringTable;',
  "```",
  "",
  "A text that counts has one key per plural category of `Intl.PluralRules` (`….one`, `….other`, and `….few`, `….many`",
  "where the language has them). *Shown by* names the components whose source uses the key.",
  "",
  "## Components (`tsazor.ui.*`)",
  "",
  "| Key | English | German | Shown by |",
  "|---|---|---|---|",
  ...Object.entries(libraryTextDefaults).map(([name, english]) => `| \`${name}\` | ${cell(english)} | ${cell(germanFrameworkTexts[`tsazor.ui.${name}`] ?? "")} | ${usedBy(name)} |`),
  "",
  "## Validation messages (`tsazor.validation.*`)",
  "",
  "`{displayName}` is the field's display name; the other placeholders are the rule's parameters.",
  "`stringLengthIncludingMinimum` is `StringLength`'s text when it has a `minimumLength` (.NET's second text); without",
  "it, `stringLength` serves both.",
  "",
  "| Key | English | German |",
  "|---|---|---|",
  ...Object.entries(VALIDATION_ENGLISH).map(([kind, english]) => `| \`${kind}\` | ${cell(english)} | ${cell(germanFrameworkTexts[`tsazor.validation.${kind}`] ?? "")} |`),
  "",
];

const out = join(repo, "docs", "library-texts.md");
const text = lines.join("\n");
if (process.argv.includes("--check")) {
  const current = existsSync(out) ? readFileSync(out, "utf8").replace(/\r\n/g, "\n") : "";
  if (current !== text) {
    console.error("docs/library-texts.md is stale: run node scripts/library-texts-doc.mjs");
    process.exit(1);
  }
  console.log("docs/library-texts.md is current.");
} else {
  writeFileSync(out, text);
  console.log(`wrote docs/library-texts.md (${Object.keys(libraryTextDefaults).length} library texts)`);
}
